#!/usr/bin/env node
// INGEST — onboard an unseen 3D asset: propose a draft profile + an evidence report.
//
//   npm run brain:ingest -- <file.glb> --family vw-type1 --id model-xxxx [--label "…"]
//                            [--root <node>] [--length 4.07] [--exclude-model <id>] [--dry]
//
// Writes src/vehicles/<family>/drafts/<id>.profile.json (NOT loaded by the app) and
// brain/vehicles/<family>/models/<id>.ingest.md. The verifier agent then renders it, fixes what is
// wrong, flips provenance.status to "verified" and moves it to models/ (auto-registered).
// Brain: brain/agents/ingestion-agent.md
import fs from 'node:fs'
import path from 'node:path'
import { ROOT } from './features.mjs'
import { ingest } from './ingest-core.mjs'

const args = process.argv.slice(2)
const file = args.find((a) => !a.startsWith('--') && /\.glb$/i.test(a))
const opt = (name) => {
  const i = args.indexOf(`--${name}`)
  return i >= 0 ? args[i + 1] : undefined
}
if (!file || !opt('family') || !opt('id')) {
  console.error('usage: brain:ingest -- <file.glb> --family <family> --id <model-id> [--label …] [--root <node>] [--length m] [--dry]')
  process.exit(1)
}
const family = opt('family')
const id = opt('id')
const result = ingest(path.resolve(file), {
  family,
  id,
  label: opt('label'),
  rootNode: opt('root'),
  length: opt('length') ? Number(opt('length')) : undefined,
  excludeModel: opt('exclude-model'),
})
const { profile, frame, groupBy, notes, candidates } = result
profile.asset.path = `/models/${path.basename(file)}`

const fmt = (n) => (typeof n === 'number' ? n.toFixed(2) : n)
const rows = candidates
  .sort((a, b) => (a.slot ?? '').localeCompare(b.slot ?? '') || b.confidence - a.confidence)
  .map((g) => {
    const f = g.sig.features
    return `| ${g.by} | \`${g.key.slice(0, 48)}\` | ${g.slot} | ${g.confidence} | ${g.runnerUp ? `${g.runnerUp.slot} ${g.runnerUp.confidence}` : '—'} | ${fmt(f.lateral)} / ${fmt(f.height)} / ${fmt(f.longitudinal)} | ${g.evidence.names.join(', ') || '—'} |`
  })
const today = new Date().toISOString().slice(0, 10)
const report = `---
id: ING-${id}
type: ingestion-report
title: Ingestion report — ${id}
status: draft
tags: [ingestion, ${family}]
links: [AGT-ingestion, ALG-classify-knn, CON-model-profile]
updated: ${today}
---

# Ingestion report — \`${id}\`

Asset: \`${path.basename(file)}\` · family \`${family}\` · generated by \`npm run brain:ingest\`.
Draft profile: \`src/vehicles/${family}/drafts/${id}.profile.json\` (**not loaded by the app** until verified).

## Frame
- native length ${frame.nativeLength.toFixed(4)} along **${frame.lengthAxis.toUpperCase()}** → scale **${profile.frame.scale}**, rotationY **${profile.frame.rotationY}**
- parts editor grouping: **${groupBy}**
- overall confidence of proposed bindings: **${profile.provenance.confidence}**

## Notes for the verifier
${notes.length ? notes.map((n) => `- ${n}`).join('\n') : '- none'}

## Proposed bindings
\`\`\`json
${JSON.stringify({ openables: profile.openables ?? [], wheels: profile.wheels ?? null, interior: profile.interior }, null, 2)}
\`\`\`

## Candidates (conf ≥ 0.25)
Features are fractions of the vehicle bbox: lateral (0 centre → 1 flank) / height / longitudinal (0 → 1 along the length axis).

| by | key | slot | conf | runner-up | lat / h / lon | name evidence |
|---|---|---|---|---|---|---|
${rows.join('\n')}

## Verification checklist (brain/agents/verifier-agent.md)
- [ ] renders at ~family length, grounded, facing +Z (nose at the front lid end)
- [ ] each proposed door/lid opens outward, hinged at the right edge, nothing torn
- [ ] wheel mounts hide the baked wheels and the swapped wheels sit on the hubs
- [ ] paint recolours the whole body and nothing else
- [ ] interior: own cabin visible, or donor cabin sits inside the glass
- [ ] parity probe recorded; status → verified; move to models/; run \`npm run brain:learn\`
`
if (args.includes('--dry')) {
  console.log(JSON.stringify(profile, null, 2))
  console.log(notes.join('\n'))
} else {
  const draftDir = path.join(ROOT, `src/vehicles/${family}/drafts`)
  const reportDir = path.join(ROOT, `brain/vehicles/${family}/models`)
  fs.mkdirSync(draftDir, { recursive: true })
  fs.mkdirSync(reportDir, { recursive: true })
  fs.writeFileSync(path.join(draftDir, `${id}.profile.json`), JSON.stringify(profile, null, 2) + '\n')
  fs.writeFileSync(path.join(reportDir, `${id}.ingest.md`), report)
  console.log(`draft  → src/vehicles/${family}/drafts/${id}.profile.json`)
  console.log(`report → brain/vehicles/${family}/models/${id}.ingest.md`)
  console.log(`confidence ${profile.provenance.confidence}; ${notes.length} note(s) for the verifier`)
}
